# تشغيل البوت
# =========================================================

def main():

    if not TOKEN:

        raise RuntimeError(
            "لم يتم العثور على TELEGRAM_BOT_TOKEN"
        )

    application = (
        Application.builder()
        .token(TOKEN)
        .build()
    )

    # /start
    application.add_handler(
        CommandHandler(
            "start",
            start
        )
    )

    # /help
    application.add_handler(
        CommandHandler(
            "help",
            help_ar
        )
    )

    # أعضاء جدد
    application.add_handler(
        MessageHandler(
            filters.StatusUpdate.NEW_CHAT_MEMBERS,
            welcome_new_member
        )
    )

    # الرسائل النصية
    application.add_handler(
        MessageHandler(
            filters.TEXT & ~filters.COMMAND,
            chat
        )
    )

    # -----------------------------------------------------
    # 🌿 ذكر كل ساعة
    # -----------------------------------------------------

    if application.job_queue is not None:

        application.job_queue.run_repeating(
            hourly_dhikr,
            interval=3600,
            first=3600
        )

    else:

        logging.warning(
            "JobQueue غير متوفر. تأكدي من requirements.txt"
        )

    print("طبوشة اشتغلت ❤️")

    application.run_polling()


# =========================================================
# البداية
# =========================================================

if __name__ == "__main__":
    main()
