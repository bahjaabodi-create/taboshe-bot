async def chat(
    update: Update,
    context: ContextTypes.DEFAULT_TYPE
):

    if not update.message:
        return

    if not update.message.text:
        return

    add_active_chat(
        update,
        context
    )

    text = update.message.text.strip()

    normalized = normalize_arabic(text)

    # -----------------------------------------------------
    # حفظ أعضاء الكروب
    # -----------------------------------------------------

    members = context.chat_data.setdefault(
        "members",
        {}
    )

    user = update.effective_user

    if user and not user.is_bot:

        members[user.id] = {
            "name": get_name(user),
            "username": user.username,
        }

    # -----------------------------------------------------
    # 🧠 صح أو غلط
    # -----------------------------------------------------

    if await handle_true_false(
        update,
        context
    ):
        return

    # -----------------------------------------------------
    # 🕌 إجابة الدين
    # -----------------------------------------------------

    if await handle_deen_answer(
        update,
        context
    ):
        return

    # -----------------------------------------------------
    # 🎮 الألعاب
    # -----------------------------------------------------

    if normalized in (
        "صح او غلط",
        "صح أو غلط"
    ):
        await start_true_false(
            update,
            context
        )
        return

    if normalized == "صراحه":
        await play_truth(
            update,
            context
        )
        return

    if normalized == "جراه":
        await play_dare(
            update,
            context
        )
        return

    if normalized == "كت":
        await play_kat(
            update,
            context
        )
        return

    if normalized in (
        "اسئله",
        "سوال",
        "سؤال"
    ):
        await play_question(
            update,
            context
        )
        return

    if normalized in (
        "نكته",
        "نكتة"
    ):
        await play_joke(
            update,
            context
        )
        return

    if normalized in (
        "هذا او هذا",
        "هذا أو هذا"
    ):
        await play_this_or_that(
            update,
            context
        )
        return

    if normalized in (
        "نرد",
        "حظ"
    ):
        await play_dice(
            update,
            context
        )
        return

    if normalized in (
        "دين",
        "سؤال ديني"
    ):
        await start_deen(
            update,
            context
        )
        return

    if normalized in (
        "زوجني",
        "زوجيني"
    ):
        await marry(
            update,
            context
        )
        return

    if normalized in (
        "نسبه",
        "نسبة"
    ):
        await love_percentage(
            update,
            context
        )
        return

    # -----------------------------------------------------
    # 🐈 قطط
    # -----------------------------------------------------

    if normalized in (
        "قطط",
        "قط"
    ):

        await update.message.reply_text(
            "🐈 معلومة عن القطط:\n\n" +
            random.choice(CAT_INFO)
        )

        return

    # -----------------------------------------------------
    # 🖤 خزان أحزان
    # -----------------------------------------------------

    if normalized == "خزان احزان":

        await update.message.reply_text(
            random.choice(
                KHAZAN_AHZAN
            )
        )

        return

    # -----------------------------------------------------
    # 🫦 نجم
    # -----------------------------------------------------

    if "🫦" in text:

        await update.message.reply_text(
            random.choice(
                LIP_REPLIES
            )
        )

        return

    # -----------------------------------------------------
    # ❤️ بحبك
    # -----------------------------------------------------

    if normalized in (
        "بحبك",
        "انا بحبك"
    ):

        await update.message.reply_text(
            random.choice(
                LOVE_YES
            )
        )

        return

    # -----------------------------------------------------
    # بتحبيني
    # -----------------------------------------------------

    if normalized in (
        "بتحبيني",
        "بتحبيني؟"
    ):

        await update.message.reply_text(
            random.choice(
                LOVE_YES
            )
        )

        return

    # -----------------------------------------------------
    # بتكرهيني
    # -----------------------------------------------------

    if normalized in (
        "بتكرهيني",
        "بتكرهيني؟"
    ):

        await update.message.reply_text(
            random.choice(
                HATE_NO
            )
        )

        return

    # -----------------------------------------------------
    # علاقة
    # -----------------------------------------------------

    if any(
        word in normalized
        for word in [
            "نرتبط",
            "ارتبط",
            "علاقه"
        ]
    ):

        await update.message.reply_text(
            random.choice(
                RELATIONSHIP_REPLIES
            )
        )

        return

    # -----------------------------------------------------
    # زواج
    # -----------------------------------------------------

    if any(
        word in normalized
        for word in [
            "تتزوجيني",
            "تزوجيني",
            "تتزوجي"
        ]
    ):

        await update.message.reply_text(
            random.choice(
                MARRIAGE_REPLIES
            )
        )

        return

    # -----------------------------------------------------
    # بوسة
    # -----------------------------------------------------

    if (
        "بوسيني" in normalized
        or "بوسه" in normalized
    ):

        await update.message.reply_text(
            random.choice(
                KISS_REPLIES
            )
        )

        return

    # -----------------------------------------------------
    # وينك
    # -----------------------------------------------------

    if normalized in (
        "وينك",
        "وينك؟",
        "وين"
    ):

        await update.message.reply_text(
            random.choice(
                WHERE_REPLIES
            )
        )

        return

    # -----------------------------------------------------
    # استغفار
    # -----------------------------------------------------

    if "استغفر الله" in normalized:

        await update.message.reply_text(
            random.choice(
                ISTAGHFAR_REPLIES
            )
        )

        return

    # -----------------------------------------------------
    # تحيات
    # -----------------------------------------------------

    greetings = [
        "مرحبا",
        "اهلا",
        "أهلا",
        "هلا",
        "هاي",
        "هيلو",
        "السلام عليكم",
    ]

    normalized_greetings = [
        normalize_arabic(x)
        for x in greetings
    ]

    if normalized in normalized_greetings:

        await update.message.reply_text(
            random.choice(
                GREETING_REPLIES
            )
        )

        return

    # -----------------------------------------------------
    # وداع
    # -----------------------------------------------------

    if normalized in (
        "باي",
        "مع السلامه",
        "تصبحون على خير",
        "تصبحي على خير",
    ):

        await update.message.reply_text(
            random.choice(
                BYE_REPLIES
            )
        )

        return

    # -----------------------------------------------------
    # طبوشة
    # -----------------------------------------------------

    if normalized == "طبوشه":

        await update.message.reply_text(
            random.choice([
                "عيوني؟ 😂",
                "نعم؟ 👀",
                "معك طبوشة 😌",
                "شو بدك مني هالمرة؟ 😂",
                "آمريني 😂",
            ])
        )

        return

    # -----------------------------------------------------
    # 🎵 يوتيوب
    # -----------------------------------------------------

    if await youtube_search(
        update,
        context
    ):
        return


