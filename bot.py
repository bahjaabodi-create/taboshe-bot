# =========================================================
# المحادثة الرئيسية
# =========================================================

async def chat(update, context):

    if not update.message:
        return

    if not update.message.text:
        return

    text = update.message.text.strip()

    lower = text.lower()

    # -----------------------------------------------------
    # جواب سؤال الدين
    # -----------------------------------------------------

    if await check_deen(update, context):
        return

    # -----------------------------------------------------
    # لعبة اعتراف أو هروب
    # -----------------------------------------------------

    confession_game = context.chat_data.get(
        "confession_game"
    )

    if confession_game:

        # إذا اللعبة تخص نفس الشخص
        if update.effective_user.id == confession_game["user_id"]:

            # إذا كان قد أجاب سابقاً، فهو الآن يختار
            if confession_game.get("answered"):

                choice = normalize_arabic(text)

                if choice == "هروب":

                    dare = random.choice(
                        ESCAPE_DARES
                    )

                    await update.message.reply_text(
                        "🏃‍♀️ هرووووب 😂\n\n"
                        "حكمك هو:\n\n"
                        f"🔥 {dare}\n\n"
                        "نفّذه يا جبان 😂"
                    )

                    context.chat_data.pop(
                        "confession_game",
                        None
                    )

                    return

                elif choice == "اعتراف":

                    question = random.choice(
                        CONFESSION_QUESTIONS
                    )

                    confession_game["question"] = question
                    confession_game["answered"] = False

                    await update.message.reply_text(
                        "😈 اخترت اعتراف؟\n\n"
                        f"❓ {question}\n\n"
                        "جاوب بصراحة 😏"
                    )

                    return

                else:

                    await update.message.reply_text(
                        "😂 لازم تختار وحدة:\n\n"
                        "❤️ اعتراف\n"
                        "🏃‍♀️ هروب"
                    )

                    return

            # إذا لم يجب بعد، أي رسالة تعتبر جواباً
            else:

                await handle_confession_answer(
                    update,
                    context
                )

                return

    # -----------------------------------------------------
    # تسجيل أعضاء الكروب
    # -----------------------------------------------------

    if (
        update.effective_chat
        and update.effective_chat.type
        in ["group", "supergroup"]
    ):

        members = context.chat_data.setdefault(
            "members",
            {}
        )

        user = update.effective_user

        if user:

            members[user.id] = {
                "name": user.first_name or "عضو",
                "username": user.username,
            }

    # -----------------------------------------------------
    # تنظيف الأمر
    # -----------------------------------------------------

    clean = lower

    if clean.startswith("/"):
        clean = clean[1:].strip()

    # -----------------------------------------------------
    # 🫦
    # -----------------------------------------------------

    if "🫦" in text:

        await update.message.reply_text(
            random.choice(
                LIP_REPLIES
            )
        )

        return

    # -----------------------------------------------------
    # اعتراف
    # -----------------------------------------------------

    if clean in [
        "اعتراف",
        "اعتراف او هروب",
        "اعتراف أو هروب",
        "اعتراف وهروب",
    ]:

        await start_confession(
            update,
            context
        )

        return

    # -----------------------------------------------------
    # هروب
    # -----------------------------------------------------

    if clean == "هروب":

        await update.message.reply_text(
            "😂 ما فيك تهرب قبل ما تبدأ اللعبة!\n"
            "اكتب «اعتراف» أول."
        )

        return

    # -----------------------------------------------------
    # دين
    # -----------------------------------------------------

    if clean in [
        "دين",
        "ديني"
    ]:

        await start_deen(
            update,
            context
        )

        return

    # -----------------------------------------------------
    # زوجني
    # -----------------------------------------------------

    if (
        "زوجني" in lower
        or "زوجيني" in lower
    ):

        await marry_someone(
            update,
            context
        )

        return

    # -----------------------------------------------------
    # كيفك
    # -----------------------------------------------------

    if (
        "كيفك" in lower
        or "كيف حالك" in lower
        or "شلونك" in lower
        or "شو اخبارك" in lower
        or "شو أخبارك" in text
    ):

        await update.message.reply_text(
            random.choice([
                "مشتهية تنتيفك شوي 😂",
                "منيحة، بس ناقصني حدا أتنرفز عليه 😭😂",
                "تمام، بس إنت كيفك يا مصدر الإزعاج؟ 😂",
                "عايشة على قيد الطبوشة 😭😂",
                "منيحة… بس لا تسأل أسئلة كتير 😂",
                "تمام، ومخططة اليوم أزعج الكروب كله 😌😂",
                "أنا بخير، بس نفسي أعمل مشكلة صغيرة 😂",
                "منيحة، إنت شو دخلك؟ 😭😂",
                "عال العال، بس حاسة إنك جاي تستفزني 😂",
                "تمام يا روحي، بس لا تقرب كتير 😂",
            ])
        )

        return

    # -----------------------------------------------------
    # بتحبيني؟
    # -----------------------------------------------------

    if (
        "بتحبيني" in lower
        or "تحبيني" in lower
    ):

        if random.choice([True, False]):

            await update.message.reply_text(
                random.choice(LOVE_YES)
            )

        else:

            await update.message.reply_text(
                random.choice(LOVE_NO)
            )

        return

    # -----------------------------------------------------
    # بتكرهيني؟
    # -----------------------------------------------------

    if (
        "بتكرهيني" in lower
        or "تكرهيني" in lower
    ):

        if random.choice([True, False]):

            await update.message.reply_text(
                random.choice(HATE_YES)
            )

        else:

            await update.message.reply_text(
                random.choice(HATE_NO)
            )

        return

    # -----------------------------------------------------
    # بحبك
    # -----------------------------------------------------

    if "بحبك" in lower:

        await update.message.reply_text(
            random.choice([
                "وأنا كمان بحبك يا روحي 😂❤️",
                "بعرف 😌 بس لا تتعلق فيني كتير 😂",
                "طبوشة كمان بتحبك 😭❤️",
                "وأنا شو بدي ساوي بهالحب هاد؟ 😭😂",
                "خلص فضحتني قدام الكروب 😂❤️",
                "يا لطيف! هيك دغري؟ 😭😂",
                "وأنا كنت ناطرة منك هالكلمة 👀❤️",
            ])
        )

        return

    # -----------------------------------------------------
    # بكرهك
    # -----------------------------------------------------

    if "بكرهك" in lower:

        await update.message.reply_text(
            random.choice([
                "وأنا شو عملتلك؟ 😭😂",
                "لااااا طبوشة حساسة 😭",
                "خلص زعلت منك 😤😂",
                "بكرا بترجع بتحبني، بعرفك 😌😂",
                "مرفوضة هاي الكلمة 😂",
            ])
        )

        return

    # -----------------------------------------------------
    # نرتبط
    # -----------------------------------------------------

    if "نرتبط" in lower:

        await update.message.reply_text(
            "💍 "
            + random.choice(
                RELATIONSHIP_REPLIES
            )
        )

        return

    # -----------------------------------------------------
    # تتزوجيني
    # -----------------------------------------------------

    if (
        "تتزوجيني" in lower
        or "تتجوزيني" in lower
        or "تتزوجني" in lower
    ):

        await update.message.reply_text(
            "💒 "
            + random.choice(
                MARRIAGE_REPLIES
            )
        )

        return

    # -----------------------------------------------------
    # بوسيني
    # -----------------------------------------------------

    if (
        "بوسيني" in lower
        or "بوسة" in lower
    ):

        await update.message.reply_text(
            random.choice(
                KISS_REPLIES
            )
        )

        return

    # -----------------------------------------------------
    # وينك
    # -----------------------------------------------------

    if "وينك" in lower:

        await update.message.reply_text(
            random.choice(
                WHERE_REPLIES
            )
        )

        return

    # -----------------------------------------------------
    # استغفر الله
    # -----------------------------------------------------

    if (
        "استغفر الله" in lower
        or "استغفرالله" in lower
    ):

        await update.message.reply_text(
            random.choice(
                ISTAGHFAR_REPLIES
            )
        )

        return

    # -----------------------------------------------------
    # اخرس
    # -----------------------------------------------------

    if clean in [
        "اخرس",
        "اخرسي",
        "اخرص",
        "اخرصي"
    ]:

        await update.message.reply_text(
            random.choice([
                "إنت بتخرس 😂",
                "خرسة بوجهك يا قليل الأدب 😭😂",
                "أنا؟ إنت ابدأ واسكت 😂",
                "طبوشة ما بتخرس… بس إنت جرّب 😂",
                "مين سمحلك تأمرني؟ 😭",
                "خرس أنت أول وبعدين منحكي 😂",
            ])
        )

        return

    # -----------------------------------------------------
    # الشتائم
    # -----------------------------------------------------

    bad_words = [
        "خرا",
        "طيزي",
        "كس",
        "زب",
        "شرموط",
        "قحبة",
        "نيك",
    ]

    if any(
        word in lower
        for word in bad_words
    ):

        await update.message.reply_text(
            random.choice(
                INSULT_REPLIES
            )
        )

        return

    # -----------------------------------------------------
    # نكتة
    # -----------------------------------------------------

    if clean in [
        "نكتة",
        "نكت"
    ]:

        await joke(
            update,
            context
        )

        return

    # -----------------------------------------------------
    # أسئلة
    # -----------------------------------------------------

    if clean in [
        "اسئلة",
        "أسئلة",
        "اسئله",
        "أسئله"
    ]:

        await questions(
            update,
            context
        )

        return

    # -----------------------------------------------------
    # نسبة
    # -----------------------------------------------------

    if clean == "نسبة":

        await love_percentage(
            update,
            context
        )

        return

    # -----------------------------------------------------
    # نرد
    # -----------------------------------------------------

    if clean == "نرد":

        await dice(
            update,
            context
        )

        return

    # -----------------------------------------------------
    # صراحة
    # -----------------------------------------------------

    if clean == "صراحة":

        await truth(
            update,
            context
        )

        return

    # -----------------------------------------------------
    # جرأة
    # -----------------------------------------------------

    if clean in [
        "جرأة",
        "جراءة",
        "جرائه"
    ]:

        await dare(
            update,
            context
        )

        return

    # -----------------------------------------------------
    # كت
    # -----------------------------------------------------

    if clean == "كت":

        await kat(
            update,
            context
        )

        return

    # -----------------------------------------------------
    # أغنية + اسم
    # -----------------------------------------------------

    if (
        clean.startswith("أغنية ")
        or clean.startswith("اغنية ")
    ):

        if clean.startswith("أغنية "):

            song_name = clean[
                len("أغنية "):
            ].strip()

        else:

            song_name = clean[
                len("اغنية "):
            ].strip()

        if song_name:

            await youtube_search(
                update,
                song_name
            )

        return

    # -----------------------------------------------------
    # أغنية بدون اسم
    # -----------------------------------------------------

    if clean in [
        "أغنية",
        "اغنية",
        "أغاني",
        "اغاني"
    ]:

        await update.message.reply_text(
            "🎵 اكتبي مثلاً:\n\n"
            "أغنية قولوا لها"
        )

        return

    # -----------------------------------------------------
    # طبوشة
    # -----------------------------------------------------

    if "طبوشة" in lower:

        await update.message.reply_text(
            random.choice([
                "يا عيون طبوشة وقلبها وروحها 😭❤️",
                "يا روحي إنت، طبوشة هون 😌❤️",
                "عيون طبوشة إلك، شو بدك؟ 🥹❤️",
                "يا قلب طبوشة إنت 😭❤️",
                "يا بعد قلب طبوشة وروحها 😂❤️",
                "نعم يا عيوني، ناديتني؟ 😌",
                "طبوشة كلها سمعتك وجاية لعندك 😂❤️",
            ])
        )

        return

    # -----------------------------------------------------
    # التحيات
    # -----------------------------------------------------

    greetings = [
        "صباح الخير",
        "صباحو",
        "مساء الخير",
        "مرحبا",
        "مراحب",
        "هاي",
        "هلا",
        "السلام عليكم",
        "سلام عليكم",
    ]

    if clean in greetings:

        await update.message.reply_text(
            random.choice(
                GREETING_REPLIES
            )
        )

        return

    # -----------------------------------------------------
    # باي
    # -----------------------------------------------------

    if clean in [
        "باي",
        "bye",
        "باي باي",
        "مع السلامة",
    ]:

        await update.message.reply_text(
            random.choice(
                BYE_REPLIES
            )
        )

        return

    # -----------------------------------------------------
    # مساعدة
    # -----------------------------------------------------

    if clean == "مساعدة":

        await help_ar(
            update,
            context
        )

        return


# =========================================================
# تشغيل البوت
# =========================================================

def main():

    token = os.environ[
        "TELEGRAM_BOT_TOKEN"
    ]

    app = (
        Application
        .builder()
        .token(token)
        .build()
    )

    app.add_handler(
        CommandHandler(
            "start",
            start
        )
    )

    app.add_handler(
        MessageHandler(
            filters.StatusUpdate.NEW_CHAT_MEMBERS,
            welcome
        )
    )

    app.add_handler(
        MessageHandler(
            filters.TEXT & ~filters.COMMAND,
            chat
        )
    )

    app.add_handler(
        MessageHandler(
            filters.TEXT & filters.COMMAND,
            chat
        )
    )

    app.run_polling()


if __name__ == "__main__":
    main()
